NARROW = set("I.,:;!|'\"()[] ")   # estos caracteres ocupan solo su ancho real + 1 px de espacio

def extents(ch, rows):
    cols = [c for line in rows for c, v in enumerate(line) if v == '#']
    if ch == ' ':
        return 0, 2                     # espacio de 3 px
    return (min(cols), max(cols)) if ch in NARROW and cols else (0, 4)

def glyph_for(rows, shift=0):
    pen = TTGlyphPen(None)
    for r, line in enumerate(rows):
        c = 0
        while c < 5:
            if line[c] == '#':
                s = c
                while c < 5 and line[c] == '#':
                    c += 1
                x0, x1 = (s - shift) * PX, (c - shift) * PX
                y1, y0 = (7 - r) * PX, (6 - r) * PX   # fila 6 = línea base
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
            else:
                c += 1
    return pen.glyph()

def gname(ch):
    return 'uni%04X' % ord(ch)

order = ['.notdef'] + [gname(ch) for ch in G]
glyphs = {'.notdef': glyph_for(('#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'))}
ADVS = {'.notdef': ADV}
for ch, rows in G.items():
    lo, hi = extents(ch, rows)
    glyphs[gname(ch)] = glyph_for(rows, lo)
    ADVS[gname(ch)] = (hi - lo + 2) * PX

cmap = {ord(ch): gname(ch) for ch in G}
for ch in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ':        # minúsculas = mayúsculas
    cmap[ord(ch.lower())] = gname(ch)
# vocales acentuadas y ñ: se dibujan como la letra base (sin tilde)
for base, accents in {'A': 'ÁÀÄÂ', 'E': 'ÉÈËÊ', 'I': 'ÍÌÏÎ', 'O': 'ÓÒÖÔ', 'U': 'ÚÙÜÛ', 'N': 'Ñ'}.items():
    for a in accents:
        cmap[ord(a)] = gname(base); cmap[ord(a.lower())] = gname(base)

fb = FontBuilder(8 * PX, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (ADVS[n], 0) for n in order})
fb.setupHorizontalHeader(ascent=8 * PX, descent=-2 * PX)
fb.setupNameTable({'familyName': 'PixelNBA', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=8 * PX, sTypoDescender=-2 * PX, usWinAscent=8 * PX, usWinDescent=2 * PX)
fb.setupPost()
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets', 'fonts', 'pixel-nba.ttf')
fb.save(out)
print('fuente generada:', os.path.normpath(out), len(G), 'glifos')
